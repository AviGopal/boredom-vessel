import { describe, it, expect, afterEach } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import * as gg from "./goal-generation";

// THE GAP-GOAL SUPPLY DOES NOT RE-SEND AN INVESTIGATION THAT DECLINED ON UNCHANGED INPUTS (the investigation damper).
// A siteless gap became "investigate and decompose gap X" every pass; each walk reached development-vessel's
// gapDecomposition, which declined needs_information on the same inputs (about five walks a day per gap, 0 reached).
// development-vessel now stamps the decline (classification_metadata.investigation_declined, its
// chronicEscalationFingerprint of the row); this supply skips the gap while the stamped readable row parts are
// unchanged, and a row change earns the retry. No parking disposition; not keyed on updated_at.
//   - MUST-FAIL: a stamped siteless gap whose row is unchanged is not turned into a goal;
//   - CONTROL: after a row change (an edit_site write) it is a goal again (a Close goal, it now has a site); after a new
//     failure lesson it is an investigation goal again; and once dv re-stamps that new state it is skipped again;
//   - CONTROL: a gap with no decline stamp is dispatched as today;
//   - PARITY: the fixtures shared byte for byte with development-vessel (its stamps generated by dv's real
//     chronicEscalationFingerprint) decide this mirror exactly.

type Gap = { id: string; summary: string; category?: string; source?: string; classification_metadata?: Record<string, unknown> };
const realFetch = globalThis.fetch;
afterEach(() => { globalThis.fetch = realFetch; });
function serve(gaps: Gap[]) {
  globalThis.fetch = (async (url: string | URL) => {
    const u = String(url);
    if (u.endsWith("/v2/impulses/resolve")) return { ok: true, status: 200, json: async () => ({ body: { gaps } }) };
    if (u.endsWith("/resolve")) return { ok: true, status: 200, json: async () => ({ body: { dispatches: [] } }) };
    return { ok: false, status: 404, json: async () => ({}) };
  }) as unknown as typeof fetch;
}
async function goals(gaps: Gap[]): Promise<Array<{ gapId: string; goalText: string }>> {
  serve(gaps);
  return (await gg.generateGapGoalCandidates("http://activity-api.test", "test-key")).map((c) => ({ gapId: c.gapId, goalText: c.goalText }));
}
type Case = { stamped: Gap | null; stamp: { fingerprint: string } | null; current: Gap; skip: boolean };
const FIX = JSON.parse(readFileSync(join(import.meta.dir, "fixtures", "investigation-decline-damper-fixtures.json"), "utf-8")) as { cases: Record<string, Case> };
/** The row the supply reads: the case's current row, an ordinary gap sentence leading its summary, and dv's stamp. */
const supplied = (name: string, c: Case): Gap => ({
  ...c.current, category: "missing_capability", source: "substrate_detected",
  summary: `The ${c.current.id} producer needs a repair so the walk reaches. ${c.current.summary}`,
  classification_metadata: { ...(c.current.classification_metadata ?? {}), ...(c.stamp ? { investigation_declined: { fingerprint: c.stamp.fingerprint, at: "2026-11-02T00:00:00.000Z", reason: "needs_information: no readable edit site" } } : {}) },
});
const C = FIX.cases;

describe("the gap-goal supply skips an investigation that declined on unchanged inputs", () => {
  it("MUST-FAIL a stamped siteless gap whose row is unchanged is not turned into a goal", async () => {
    const out = await goals([supplied("u", C["unchanged_row_is_skipped"]!), supplied("n", C["no_stamp_is_dispatched"]!)]);
    expect(out.map((o) => o.gapId)).toEqual([C["no_stamp_is_dispatched"]!.current.id]);
  });

  it("CONTROL after a row change it is a goal again, and once re-stamped it is skipped again", async () => {
    const site = await goals([supplied("s", C["an_edit_site_write_earns_the_retry"]!)]);
    expect(site.map((o) => o.gapId)).toEqual(["fixture-siteless-b"]);
    expect(site[0]!.goalText).toStartWith("Close substrate gap fixture-siteless-b");
    const lesson = await goals([supplied("l", C["a_new_failure_lesson_earns_the_retry"]!)]);
    expect(lesson.map((o) => o.gapId)).toEqual(["fixture-siteless-c"]);
    expect(lesson[0]!.goalText).toStartWith("investigate and decompose gap fixture-siteless-c");
    expect(await goals([supplied("r", C["the_retry_restamps_and_skips_again"]!)])).toEqual([]);
  });

  it("CONTROL a gap with no decline stamp, or an unparseable one, is dispatched as today", async () => {
    expect((await goals([supplied("n", C["no_stamp_is_dispatched"]!)])).map((o) => o.gapId)).toEqual(["fixture-siteless-f"]);
    expect((await goals([supplied("g", C["an_unparseable_stamp_is_dispatched"]!)])).map((o) => o.gapId)).toEqual(["fixture-siteless-g"]);
  });
});

describe("investigation damper: the fixtures shared with development-vessel", () => {
  const cases = Object.entries(C);
  it("CONTROL the shared fixture set is present", () => { expect(cases.length).toBeGreaterThan(0); });
  for (const [name, c] of cases) {
    it(`${c.skip ? "skipped" : "dispatched"}: ${name}`, async () => {
      const row = supplied(name, c);
      expect(gg.investigationDeclinedUnchanged(row)).toBe(c.skip);
      expect((await goals([row])).some((o) => o.gapId === c.current.id)).toBe(!c.skip);
    });
  }
});
